_GN_RHS_EXPR = rf"{_GN_RHS_TERM}(?:\s*\+\s*{_GN_RHS_TERM})*"


def find_fuchsia_root(explicit_dir: str | None = None) -> pathlib.Path:
    """Resolves the Fuchsia checkout root directory."""
    if explicit_dir:
        return pathlib.Path(explicit_dir).resolve()
    env_dir = os.environ.get("FUCHSIA_DIR")
    if env_dir and os.path.isdir(env_dir):
        return pathlib.Path(env_dir).resolve()

    # Walk up from script location and current working directory
    for start in (pathlib.Path(__file__).resolve().parent, pathlib.Path.cwd()):
        curr = start
        while curr != curr.parent:
            if (curr / ".jiri_root").exists() or (
                curr / "build/tools/bazel2gn"
            ).exists():
                return curr
            curr = curr.parent

    # Fallback: relative to //build/beads/.agent/skills/analyzing_migration_dag/scripts/
    return pathlib.Path(__file__).resolve().parents[5]


def normalize_label(label: str, current_pkg: str = "") -> str:
    """Normalizes a GN label into canonical `//pkg/path:target_name` form.

    Strips toolchain suffixes `(//build/toolchain:...)`, resolves relative
    package paths (`..`, `.`, shorthand `:foo`, or `//a/b` without a colon),
    and strips `.actual` subtarget suffixes.
    """
    label = label.split("(")[0].strip()
    if not label:
        return ""
    explicit_target: str | None = None
    if label.startswith(":"):
        pkg_part = current_pkg
        explicit_target = label[1:]
    elif not label.startswith("//"):
        if ":" in label:
            subpath, explicit_target = label.split(":", 1)
            pkg_part = f"{current_pkg}/{subpath}" if current_pkg else subpath
        else:
            pkg_part = f"{current_pkg}/{label}" if current_pkg else label
    elif ":" in label:
        pkg_part, explicit_target = label.split(":", 1)
    else:
        pkg_part = label

    norm_rel = os.path.normpath(pkg_part.lstrip("/")).lstrip("/")
    if norm_rel in ("", "."):
        norm_pkg = "//"
    else:
        norm_pkg = f"//{norm_rel}"

    target_part = (
        explicit_target
        if explicit_target is not None
        else norm_pkg.rstrip("/").split("/")[-1]
    )
    # GN SDK/Zircon wrapper templates (e.g. zx_library, sdk_source_set, fidl)
    # synthesize internal `.actual` subtargets that correspond to the base
    # target name in BUILD.bazel.
    if target_part.endswith(".actual"):
        target_part = target_part[: -len(".actual")]
    return f"{norm_pkg}:{target_part}"


def split_label(label: str) -> tuple[str, str]:
    """Splits a GN label into `(canonical_pkg, target_name)`."""
    norm = normalize_label(label)
    if not norm or ":" not in norm:
        return "", ""
    pkg, target = norm.split(":", 1)
    return pkg, target


@functools.lru_cache(maxsize=8)
def load_third_party_map(fuchsia_root: pathlib.Path) -> frozenset[str]:
    """Loads the set of normalized GN third-party target labels mapped in bazel2gn."""
    map_path = fuchsia_root / "build/tools/bazel2gn/third_party_target_map.json"
    if map_path.exists():
        with open(map_path, "r") as f:
            data = json.load(f)
            return frozenset(
                normalize_label(v) for v in data.values() if normalize_label(v)
            )
    return frozenset()


def is_ignored_gn_target(label: str) -> bool:
    """Returns True if `label` is build-system plumbing or an out-of-scope E2E test."""
    for prefix in IGNORED_GN_PREFIXES:
        if label.startswith(prefix):
            return True
    for substr in IGNORED_GN_SUBSTRINGS:
        if substr in label:
            return True
    return False


def _extract_rhs_items(
    rhs_expr: str, var_lists: dict[str, list[str]]
) -> list[str]:
    """Extracts string literals and resolved variable lists from a GN RHS expression."""
    items: list[str] = []
    # Extract all inline bracketed lists [...] in the RHS expression
    for bracket_match in re.finditer(r"\[([^\]]*)\]", rhs_expr):
        items.extend(re.findall(r'"([^"]+)"', bracket_match.group(1)))
    # Remove bracketed segments and extract any variable identifiers
    outside_brackets = re.sub(r"\[[^\]]*\]", " ", rhs_expr)
    for var_match in re.finditer(
        r"\b([a-zA-Z_][a-zA-Z0-9_]*)\b", outside_brackets
    ):
        items.extend(var_lists.get(var_match.group(1), []))
    return items


def _extract_gn_dep_labels(
    body: str,
    attr_names: tuple[str, ...],
    var_lists: dict[str, list[str]],
    pkg: str,
) -> set[str]:
    """Extracts and normalizes GN dependency labels assigned to `attr_names` in `body`."""
    attr_pattern = "|".join(attr_names)
    raw_items: list[str] = []
    for m in re.finditer(
        rf"\b(?:{attr_pattern})\s*\+?=\s*({_GN_RHS_EXPR})", body
    ):
        raw_items.extend(_extract_rhs_items(m.group(1), var_lists))

    # Note: GN files importing //build/icu/config.gni reference ICU targets
    # via "${icu_root}:..." (where icu_root defaults to "//third_party/icu/default").
    # Because unexpanded "$var" strings are skipped below, we resolve ${icu_root}
    # explicitly so third-party ICU dependencies and blockers are not dropped.
    resolved: set[str] = set()
    for item in raw_items:
        if "${icu_root}" in item:
            item = item.replace("${icu_root}", "//third_party/icu/default")
        if not item.startswith("$"):
            norm = normalize_label(item, pkg)
            if norm and not is_ignored_gn_target(norm):
                resolved.add(norm)
    return resolved


@functools.lru_cache(maxsize=512)
def parse_build_gn_targets_and_tests(
    fuchsia_root: pathlib.Path, pkg: str
) -> dict[str, dict[str, Any]]:
    """Parses <pkg>/BUILD.gn to extract target types, deps, test_deps, and unit test targets."""
    rel_dir = pkg.lstrip("/")
    build_gn_path = fuchsia_root / rel_dir / "BUILD.gn"
    results: dict[str, dict[str, Any]] = {}
    if not build_gn_path.exists():
        return results

    with open(build_gn_path, "r") as f:
        content = f.read()

    # Strip comments
    lines = [line.split("#", 1)[0] for line in content.splitlines()]
    clean_content = "\n".join(lines)

    # Extract file-scope list variables (e.g., lib_deps = [ ... ], lib_deps += common_deps + [ ... ])
    var_lists: dict[str, list[str]] = {}
    for vm in re.finditer(
        rf"\b([a-zA-Z_][a-zA-Z0-9_]*)\s*\+?=\s*({_GN_RHS_EXPR})",
        clean_content,
    ):
        vname = vm.group(1)
        if vname not in GN_RESERVED_LIST_ATTRS:
            var_lists.setdefault(vname, []).extend(
                _extract_rhs_items(vm.group(2), var_lists)
            )

    # Match rule("name") { ... }
    pattern = re.compile(r'\b([a-zA-Z0-9_]+)\s*\(\s*"([^"]+)"\s*\)\s*\{')
    for m in pattern.finditer(clean_content):
        rule_type = m.group(1)
        if rule_type in GN_NON_TARGET_BLOCKS:
            continue
        target_name = m.group(2)
        brace_start = m.end() - 1
        depth = 0
        end_idx = brace_start
        in_string = False
        for i in range(brace_start, len(clean_content)):
            ch = clean_content[i]
            if ch == '"' and (i == 0 or clean_content[i - 1] != "\\"):
                in_string = not in_string
            elif not in_string:
                if ch == "{":
                    depth += 1
                elif ch == "}":
                    depth -= 1
                    if depth == 0:
                        end_idx = i
                        break
        body = clean_content[brace_start + 1 : end_idx]

        # Extract production dependency attributes (GN_PROD_DEP_ATTRS) and test_deps (GN_TEST_DEP_ATTRS)
        deps: set[str] = set(IMPLICIT_TEMPLATE_DEPS.get(rule_type, []))
        deps |= _extract_gn_dep_labels(body, GN_PROD_DEP_ATTRS, var_lists, pkg)
        test_deps: set[str] = _extract_gn_dep_labels(
            body, GN_TEST_DEP_ATTRS, var_lists, pkg
        )

        # host_test_data rules that copy "${icu_root}/common/icudtl.dat" via
        # `sources` (without a `deps` entry) implicitly depend on the ICU data target.
        if "${icu_root}" in body and rule_type == "host_test_data":
            deps.add("//third_party/icu/default:icudata")

        # Extract alternate names (output_name, crate name, or bazel_target for bazel_host_tool)
        alt_names: set[str] = set()
        for name_match in re.finditer(
            r'\b(?:output_name|name|bazel_target)\s*=\s*"([^"$]+)"', body
        ):
            raw_alt = name_match.group(1).split(":")[-1]
            if raw_alt:
                alt_names.add(raw_alt)

        with_unit_tests = bool(
            re.search(r"\bwith_unit_tests\s*=\s*true\b", body)
        )
        # Source files (literal or via list variables). Used to associate a
        # standalone test that recompiles a target's sources (e.g.
        # `rustc_test("foo_test") { sources = _sources }`) with that target.
        sources: set[str] = set()
        for src_match in re.finditer(
            rf"\bsources\s*\+?=\s*({_GN_RHS_EXPR})", body
        ):
            sources.update(
                s
                for s in _extract_rhs_items(src_match.group(1), var_lists)
                if not s.startswith("$")
            )
        full_label = f"{pkg}:{target_name}"
        deps.discard(full_label)
        test_deps.discard(full_label)
        is_test = (
            rule_type in GN_TEST_RULE_TYPES
            or target_name in GN_TEST_TARGET_NAMES
        )
        if full_label in results:
            existing = results[full_label]
            # The same name can legitimately appear more than once when a
            # target is defined in mutually exclusive `if/else` branches (same
            # rule type, or a concrete rule on one side and a `group` stub on
            # the other). Different wrapper templates can also reuse a name
            # argument while generating *different* labels, e.g. in
            # //src/storage/fxfs/BUILD.gn `rustc_binary("fxfs")`,
            # `fs_test_config("fxfs")` and `fs_test_suite("fxfs")`. Merging
            # those would attach test-suite deps to the binary and create false
            # cycles, so only merge in the if/else cases and otherwise keep the
            # first concrete definition.
            existing_type = existing["rule_type"]
            if existing_type == "group" and rule_type != "group":
                existing["rule_type"] = rule_type
            elif not (
                existing_type == rule_type
                or "group" in (existing_type, rule_type)
            ):
                continue
            existing["deps"].update(deps)
            existing["test_deps"].update(test_deps)
            existing["alt_names"].update(alt_names)
            existing["sources"].update(sources)
            existing["with_unit_tests"] = (
                existing["with_unit_tests"] or with_unit_tests
            )
            existing["is_test"] = existing["is_test"] or is_test
        else:
            results[full_label] = {
                "rule_type": rule_type,
                "target_name": target_name,
                "deps": deps,
                "test_deps": test_deps,
                "alt_names": alt_names,
                "sources": sources,
                "with_unit_tests": with_unit_tests,
                "is_test": is_test,
            }

        # `ffx_plugin("foo")` (//src/developer/ffx/build/ffx_plugin.gni) also
        # generates a standalone `rustc_library("foo_args")` built only from
        # `args_deps` (plus `<d>_args` for each `plugin_deps` entry). Other
        # crates often depend on just `:foo_args`, so model it as its own node:
        # aliasing it to the whole plugin would add the plugin's deps and can
        # create false cycles (e.g. `target_formatter` -> `ffx_list_args`).
        if rule_type == "ffx_plugin":
            args_label = f"{full_label}_args"
            if args_label not in results:
                args_deps = _extract_gn_dep_labels(
                    body, ("args_deps",), var_lists, pkg
                )
                args_deps |= {
                    f"{d}_args"
                    for d in _extract_gn_dep_labels(
                        body, ("plugin_deps",), var_lists, pkg
                    )
                }
                results[args_label] = {
                    "rule_type": "rustc_library",
                    "target_name": f"{target_name}_args",
                    "deps": args_deps,
                    "test_deps": set(),
                    "alt_names": set(),
                    "sources": set(),
                    "with_unit_tests": False,
                    "is_test": False,
                }

    # Resolve implicit `:<name>_test` subtargets generated by `with_unit_tests = true`
    implicit_test_map: dict[str, str] = {}
    for full_label, info in results.items():
        if info["with_unit_tests"]:
            implicit_test_label = f"{full_label}_test"
            if implicit_test_label not in results:
                implicit_test_map[implicit_test_label] = full_label

    if implicit_test_map:
        for full_label, info in results.items():
            info["deps"] = {
                implicit_test_map.get(d, d)
                for d in info["deps"]
                if implicit_test_map.get(d, d) != full_label
            }
            info["test_deps"] = {
                implicit_test_map.get(d, d)
                for d in info["test_deps"]
                if implicit_test_map.get(d, d) != full_label
            }

    return results


# Characters that GN templates use to join an invocation name with a generated
# subtarget suffix (e.g. `foo_rust`, `foo-component`, `foo.actual`).
GENERATED_SUBTARGET_SEPARATORS = ("_", "-", ".")


def resolve_generated_subtarget(
    label: str, pkg_targets: dict[str, dict[str, Any]]
) -> str:
    """Maps a template-generated subtarget label onto its defining invocation.

    GN templates synthesize labels that never appear literally in BUILD.gn,
    e.g. `fidl("foo")` -> `:foo_rust` / `:foo_cpp` / `:foo_banjo_c`,
    `ffx_plugin("foo")` -> `:foo_tests` / `:foo_args`, or
    `rustc_library("foo") { with_unit_tests = true }` -> `:foo_test`.
    Without this mapping such labels become edge-less leaf nodes that lose the
    template's deps. If `label` is not defined in `pkg_targets`, returns the
    defined target in the same package whose name is the longest prefix of
    `label`'s name followed by a separator; otherwise returns `label` unchanged.
    """
    if label in pkg_targets:
        return label
    pkg, target = split_label(label)
    best_label, best_len = label, 0
    for cand_label, info in pkg_targets.items():
        name = info["target_name"]
        if (
            len(name) > best_len
            and len(target) > len(name)
            and target.startswith(name)
            and target[len(name)] in GENERATED_SUBTARGET_SEPARATORS
            and cand_label.startswith(f"{pkg}:")
        ):
            best_label, best_len = cand_label, len(name)
    return best_label


@functools.lru_cache(maxsize=512)
def _read_clean_bazel_file(bazel_path: pathlib.Path) -> str | None:
    """Reads `<pkg>/BUILD.bazel` and strips `#` comments, caching the result."""
    if not bazel_path.exists():
        return None
    with open(bazel_path, "r") as f:
        return "\n".join(
            line.split("#", 1)[0] for line in f.read().splitlines()
        )


def check_bazel_status(
    fuchsia_root: pathlib.Path,
    label: str,
    third_party_map: frozenset[str] | set[str],
    gn_info: dict[str, Any] | None,
) -> tuple[str, str]:
    """Classifies a target into:
    - MIGRATED_READY
    - UNMIGRATED_IN_SCOPE
    - HARD_BLOCKER
    """
    pkg, target = split_label(label)
    rel_dir = pkg.lstrip("/")

    # Check custom blocker templates in GN
    if gn_info and gn_info.get("rule_type") in CUSTOM_BLOCKER_GNI:
        return (
            "HARD_BLOCKER",
            f"Uses custom GN template `{gn_info['rule_type']}` ({CUSTOM_BLOCKER_GNI[gn_info['rule_type']]})",
        )

    # Host tools wrapped with bazel_host_tool() in BUILD.gn are already migrated to Bazel.
    if gn_info and gn_info.get("rule_type") == "bazel_host_tool":
        return (
            "MIGRATED_READY",
            f"Wrapped by bazel_host_tool in {pkg}/BUILD.gn",
        )

    # Vendored third-party Rust crates (//third_party/rust_crates:*) and Go
    # libraries (//third_party/golibs:*) have auto-generated Bazel targets
    # mapped natively by bazel2gn (see //build/tools/bazel2gn/constants.go).
    # For subpackages under //third_party/rust_crates/* (such as forks/ or
    # intree/), only fast-path if they are in the root rust_crates package or
    # already have a BUILD.bazel file.
    if pkg == "//third_party/rust_crates":
        return (
            "MIGRATED_READY",
            "Available in //third_party/rust_crates/vendor",
        )
    if pkg.startswith("//third_party/golibs"):
        return ("MIGRATED_READY", "Available in //third_party/golibs")
    if label in third_party_map:
        return ("MIGRATED_READY", "Mapped in third_party_target_map.json")

    bazel_path = fuchsia_root / rel_dir / "BUILD.bazel"
    bcontent = _read_clean_bazel_file(bazel_path)
    if bcontent is not None:
        candidate_names = [target]
        if gn_info and gn_info.get("alt_names"):
            for alt in sorted(gn_info["alt_names"]):
                if alt not in candidate_names:
                    candidate_names.append(alt)
        if "fidl_library(" in bcontent:
            for fidl_suffix in FIDL_BACKEND_SUFFIXES:
                if target.endswith(fidl_suffix):
                    candidate_names.append(target[: -len(fidl_suffix)])
        for ffx_suffix in FFX_PLUGIN_SUFFIXES:
            if target.endswith(ffx_suffix):
                candidate_names.append(target[: -len(ffx_suffix)])
        # If target is an implicit `:<name>_test` generated by `with_unit_tests = true` in GN
        # and BUILD.bazel uses `with_host_unit_tests = True` or `with_unit_tests = True`:
        if target.endswith("_test") and (
            "with_host_unit_tests" in bcontent or "with_unit_tests" in bcontent
        ):
            candidate_names.append(target[: -len("_test")])
        # Also if target is a GN forwarding group (e.g. group("rust") { public_deps = [ ":fuchsia-inspect" ] })
        # in a package that already has BUILD.bazel containing the target's same-package dep:
        if gn_info and gn_info.get("rule_type") == "group":
            for dep_label in sorted(gn_info.get("deps", set())):
                dep_pkg, dep_target = split_label(dep_label)
                if dep_pkg == pkg and dep_target not in candidate_names:
                    candidate_names.append(dep_target)
        found_name = None
        for cand in candidate_names:
            if re.search(rf'\bname\s*=\s*"{re.escape(cand)}"', bcontent):
                found_name = cand
                break
        if found_name:
            return (
                "MIGRATED_READY",
                f"Defined in {pkg}/BUILD.bazel (:{found_name})",
            )

    # If not in BUILD.bazel and under //third_party/, check if it's an external git repo / blocker
    if pkg.startswith("//third_party/"):
        return (
            "HARD_BLOCKER",
            f"Third-party target `{label}` has no BUILD.bazel and is not in third_party_target_map.json",
        )

    return ("UNMIGRATED_IN_SCOPE", f"No Bazel target yet in {pkg}/BUILD.bazel")


def build_full_dag_with_tests(
    fuchsia_root: pathlib.Path,
    start_labels: list[str],
    max_depth: int = -1,
    include_upstream_tests: bool = False,
) -> tuple[
    dict[str, set[str]],
    dict[str, dict[str, Any]],
    dict[str, tuple[str, str]],
    dict[str, int],
    set[str],
]:
    """Recursively discovers production deps (+ unit test deps for root pkg, or all pkgs if
    include_upstream_tests=True), pruning at MIGRATED_READY nodes and stopping expansion
    when max_depth >= 0 and depth >= max_depth.
    Depth is measured in cross-package hops (same-package targets share the package's depth).
    """
    third_party_map = load_third_party_map(fuchsia_root)
    edges: dict[str, set[str]] = defaultdict(set)
    nodes: set[str] = set(start_labels)
    depths: dict[str, int] = {lbl: 0 for lbl in start_labels}
    truncated_at_depth: set[str] = set()
    statuses: dict[str, tuple[str, str]] = {}

    gn_cache: dict[str, dict[str, dict[str, Any]]] = {}
    all_gn_info: dict[str, dict[str, Any]] = {}

    def get_pkg_gn(pkg: str) -> dict[str, dict[str, Any]]:
        """Returns cached parsed BUILD.gn target metadata for `pkg` and merges it into `all_gn_info`."""
        if pkg not in gn_cache:
            gn_cache[pkg] = parse_build_gn_targets_and_tests(fuchsia_root, pkg)
            all_gn_info.update(gn_cache[pkg])
        return gn_cache[pkg]

    queue: deque[tuple[str, int]] = deque([(lbl, 0) for lbl in start_labels])
    visited_nodes: set[str] = set()
    root_pkg, _ = split_label(start_labels[0])

    def is_same_pkg_family(pkg_a: str, pkg_b: str) -> bool:
        """Returns True if pkg_a and pkg_b are the same GN package or one is the
        companion `tests/` or `test/` subdirectory of the other (e.g. `//foo` and
        `//foo/tests`). Companion test subdirectories are treated as part of the
        same logical package so they share the same cross-package hop depth and
        unit-test expansion scope.
        """
        return (
            pkg_a == pkg_b
            or pkg_b == f"{pkg_a}/tests"
            or pkg_b == f"{pkg_a}/test"
            or pkg_a == f"{pkg_b}/tests"
            or pkg_a == f"{pkg_b}/test"
        )

    def enqueue_node(
        target_label: str, next_depth: int, same_pkg_hop: bool
    ) -> None:
        """Enqueues `target_label` using 0-1 BFS ordering (`appendleft` for 0-cost
        same-package hops, `append` for +1 cross-package hops) and re-expands if
        a shorter path improves a previously truncated node's depth.
        """
        improved = (
            target_label not in depths or next_depth < depths[target_label]
        )
        if improved:
            depths[target_label] = next_depth
            if target_label in truncated_at_depth:
                truncated_at_depth.discard(target_label)
                visited_nodes.discard(target_label)
        if target_label not in nodes or (
            improved and target_label not in visited_nodes
        ):
            nodes.add(target_label)
            if same_pkg_hop:
                queue.appendleft((target_label, next_depth))
            else:
                queue.append((target_label, next_depth))

    test_index_cache: dict[str, dict[str, set[str]]] = {}

    def is_test_aggregator(info: dict[str, Any]) -> bool:
        """Returns True for `group("tests")`-style targets that only aggregate
        other tests (often of unrelated subdirectories) rather than testing a
        specific library."""
        return (
            info["rule_type"] == "group"
            and info["target_name"] in GN_TEST_AGGREGATOR_NAMES
        )

    def family_test_index(pkg: str) -> dict[str, set[str]]:
        """Maps each production target in `pkg`'s package family to the test
        targets in `<pkg>`, `<pkg>/tests`, or `<pkg>/test` that exercise it.

        A test "exercises" a production target if either:
          - it depends on it directly or through a chain of other test targets
            in the same family (e.g. `fuchsia_unittest_package` -> `:foo_test`
            -> `:foo`, or `rustc_test` -> `group("test_files")` ->
            `host_test_data` -> `:foo`), or
          - it is defined in the same BUILD.gn and compiles some of the same
            `sources` (e.g. `rustc_test("foo_test") { sources = _sources }`
            next to `rustc_binary("foo") { sources = _sources }`).
        Aggregator groups are never followed, so a root `group("tests")` that
        collects tests from child directories does not pull in downstream
        consumers or unrelated siblings of the analyzed target.
        """
        if pkg in test_index_cache:
            return test_index_cache[pkg]
        index: dict[str, set[str]] = defaultdict(set)
        test_index_cache[pkg] = index
        if pkg.startswith("//third_party/"):
            return index
        family_targets: dict[str, dict[str, Any]] = {}
        for fam_pkg in (pkg, f"{pkg}/tests", f"{pkg}/test"):
            family_targets.update(get_pkg_gn(fam_pkg))

        for t_label, t_info in sorted(family_targets.items()):
            if not t_info["is_test"] or is_test_aggregator(t_info):
                continue
            t_pkg, _ = split_label(t_label)
            if "e2e" in t_info["target_name"] and t_pkg != root_pkg:
                continue
            if t_info["sources"]:
                for p_label, p_info in family_targets.items():
                    if (
                        not p_info["is_test"]
                        and split_label(p_label)[0] == t_pkg
                        and t_info["sources"] & p_info["sources"]
                    ):
                        index[p_label].add(t_label)
            seen = {t_label}
            stack = [t_label]
            while stack:
                cur_info = family_targets[stack.pop()]
                for d in sorted(cur_info["deps"] | cur_info["test_deps"]):
                    d_pkg, _ = split_label(d)
                    if d_pkg.startswith("//third_party/"):
                        continue
                    d = resolve_generated_subtarget(d, get_pkg_gn(d_pkg))
                    if d in seen or d not in family_targets:
                        continue
                    seen.add(d)
                    d_info = family_targets[d]
                    if is_test_aggregator(d_info):
                        continue
                    if d_info["is_test"]:
                        stack.append(d)
                    else:
                        index[d].add(t_label)
        return index

    def expand_unit_tests_for(target: str, curr_depth: int) -> None:
        """Enqueues the test targets in `target`'s package family that exercise it."""
        t_pkg, _ = split_label(target)
        for t_label in sorted(family_test_index(t_pkg).get(target, set())):
            enqueue_node(t_label, curr_depth, True)

    while queue:
        curr, curr_depth = queue.popleft()
        if curr in visited_nodes:
            continue
        visited_nodes.add(curr)

        pkg, _ = split_label(curr)
        include_tests_here = include_upstream_tests or is_same_pkg_family(
            pkg, root_pkg
        )

        # Fast-path prune before parsing BUILD.gn if package is third_party/rust_crates or golibs
        fast_status = check_bazel_status(
            fuchsia_root, curr, third_party_map, None
        )
        if fast_status[0] == "MIGRATED_READY":
            statuses[curr] = fast_status
            # If the root package's production target is already migrated, still
            # discover unmigrated tests that exercise it.
            if curr_depth == 0 and include_tests_here:
                expand_unit_tests_for(curr, curr_depth)
            continue

        # Also avoid parsing third_party BUILD.gn if it's a known third_party blocker without BUILD.bazel
        if fast_status[0] == "HARD_BLOCKER" and pkg.startswith(
            "//third_party/"
        ):
            statuses[curr] = fast_status
            continue

        pkg_targets = get_pkg_gn(pkg)
        status = check_bazel_status(
            fuchsia_root, curr, third_party_map, pkg_targets.get(curr)
        )
        statuses[curr] = status

        # Prune already-migrated targets!
        if status[0] == "MIGRATED_READY":
            if curr_depth == 0 and include_tests_here:
                expand_unit_tests_for(curr, curr_depth)
            continue

        curr_deps: set[str] = set()
        if curr in pkg_targets:
            curr_deps = set(pkg_targets[curr]["deps"])
            if include_tests_here:
                curr_deps |= pkg_targets[curr]["test_deps"]

        # Check if we hit max_depth (only truncate cross-package expansion at max_depth)
        if max_depth >= 0 and curr_depth >= max_depth:
            if curr_deps:
                truncated_at_depth.add(curr)
            continue

        # Expand curr's dependencies from BUILD.gn
        # Same-package targets stay at curr_depth; cross-package targets increment depth by 1
        for d in sorted(curr_deps):
            d_pkg, _ = split_label(d)
            # Map template-generated subtargets (e.g. `<fidl>_rust`,
            # `<plugin>_tests`, `<name>_test`) onto the template invocation
            # that defines them, so they inherit its deps and status.
            if not d_pkg.startswith("//third_party/"):
                d = resolve_generated_subtarget(d, get_pkg_gn(d_pkg))
            if d != curr:
                edges[curr].add(d)
            same_family = is_same_pkg_family(pkg, d_pkg)
            next_depth = curr_depth if same_family else curr_depth + 1
            enqueue_node(d, next_depth, same_family)

        # Pull in the tests that exercise `curr` (root package family only, or
        # every in-tree package when include_upstream_tests is set).
        if include_tests_here:
            expand_unit_tests_for(curr, curr_depth)

    for n in sorted(nodes):
        if n not in statuses:
            statuses[n] = check_bazel_status(
                fuchsia_root, n, third_party_map, all_gn_info.get(n)
            )

    return edges, all_gn_info, statuses, depths, truncated_at_depth


def kahn_topological_sort(
    edges: dict[str, set[str]], statuses: dict[str, tuple[str, str]]
) -> tuple[list[list[str]], dict[str, set[str]], dict[str, int], bool]:
    """Computes Kahn's topological sort waves over all non-MIGRATED_READY nodes.
    Note: If A depends on B (`B in edges[A]`), B must be migrated BEFORE A.
    So in the migration order graph:
      prerequisite_of[A] = { B | B in edges[A] and B is not MIGRATED_READY }
      in_degree[A] = len(prerequisite_of[A])
    Returns `(waves, prereqs, initial_in_degree, has_cycle)`.
    """
    active_nodes = {
        n for n, (st, _) in statuses.items() if st != "MIGRATED_READY"
    }
    prereqs: dict[str, set[str]] = {
        n: {
            dep
            for dep in edges.get(n, set())
            if dep in active_nodes and dep != n
        }
        for n in active_nodes
    }
    initial_in_degree: dict[str, int] = {
        n: len(prereqs[n]) for n in active_nodes
    }
    current_in_degree: dict[str, int] = dict(initial_in_degree)

    waves: list[list[str]] = []
    remaining = set(active_nodes)
    has_cycle = False

    while remaining:
        zero_nodes = sorted([n for n in remaining if current_in_degree[n] == 0])
        if not zero_nodes:
            has_cycle = True
            waves.append(sorted(list(remaining)))
            break
        waves.append(zero_nodes)
        for z in zero_nodes:
            remaining.remove(z)
        for n in remaining:
            for z in zero_nodes:
                if z in prereqs[n]:
                    current_in_degree[n] -= 1

    return waves, prereqs, initial_in_degree, has_cycle


def _pkg_prefix(pkg: str, parts_count: int = 3) -> str:
    """Returns the leading `parts_count` directory segments of a GN package (e.g. `//src/lib/icu`)."""
    parts = [p for p in pkg.strip("/").split("/") if p]
    return "//" + "/".join(parts[:parts_count])


def _format_cl_summary(batch_pkgs: list[str]) -> str:
    """Formats a short human-readable summary of package paths for a CL header."""
    short_names = []
    for p in batch_pkgs:
        parts = [x for x in p.strip("/").split("/") if x]
        if len(parts) >= 2:
            short_names.append("/".join(parts[-2:]))
        elif parts:
            short_names.append(parts[-1])
    return ", ".join(f"`{s}`" for s in short_names)


def plan_stacked_cls(
    edges: dict[str, set[str]],
    statuses: dict[str, tuple[str, str]],
    wave_of: dict[str, int],
    max_pkgs_per_cl: int = 5,
) -> tuple[
    list[tuple[str, list[str]]],
    list[tuple[str, list[str]]],
    dict[str, list[str]],
    dict[str, set[str]],
]:
    """Groups unmigrated targets by BUILD.gn package and packs packages into
    reviewable stacked CLs (up to max_pkgs_per_cl packages per CL) in strict
    topological order, partitioned into:
      - Phase A: Unblocked In-Tree Targets (can land immediately)
      - Phase B: Hard Blockers & Blocked Downstream Stack (packed in a single
        topological pass so blockers and blocked targets respect true dependency order)
    """
    pkg_targets: dict[str, list[str]] = defaultdict(list)
    pkg_edges: dict[str, set[str]] = defaultdict(set)

    for u, (st, _) in sorted(statuses.items()):
        if st in ("UNMIGRATED_IN_SCOPE", "HARD_BLOCKER"):
            u_pkg, _ = split_label(u)
            pkg_targets[u_pkg].append(u)
            for v in edges.get(u, set()):
                if statuses.get(v, ("", ""))[0] in (
                    "UNMIGRATED_IN_SCOPE",
                    "HARD_BLOCKER",
                ):
                    v_pkg, _ = split_label(v)
                    if v_pkg != u_pkg:
                        pkg_edges[u_pkg].add(v_pkg)

    # Order targets within each package topologically using wave_of
    for p, tlist in pkg_targets.items():
        tlist.sort(key=lambda x: (wave_of.get(x, 0), x))

    pkg_is_blocker = {
        p: any(statuses[t][0] == "HARD_BLOCKER" for t in tlist)
        for p, tlist in pkg_targets.items()
    }
    # A package is blocked if it contains a HARD_BLOCKER or can reach one via
    # package edges. Compute this by walking reverse package edges outward from
    # every blocker package. Unlike a memoized recursive DFS, this never caches
    # a provisional answer while inside a package-level cycle, so the result is
    # correct and independent of set iteration order (PYTHONHASHSEED).
    reverse_pkg_edges: dict[str, set[str]] = defaultdict(set)
    for p, dep_pkgs in pkg_edges.items():
        for q in dep_pkgs:
            reverse_pkg_edges[q].add(p)
    blocked_set = {p for p, is_blocker in pkg_is_blocker.items() if is_blocker}
    frontier = deque(sorted(blocked_set))
    while frontier:
        q = frontier.popleft()
        for p in sorted(reverse_pkg_edges.get(q, set())):
            if p not in blocked_set:
                blocked_set.add(p)
                frontier.append(p)
    pkg_blocked: dict[str, bool] = {p: p in blocked_set for p in pkg_targets}

    def affinity_score(
        candidate: str, current_batch: list[str]
    ) -> tuple[int, int, int, int, str]:
        """Scores how closely `candidate` belongs in the same CL as `current_batch`.

        Returns a 5-tuple (lower is better):
          1. `same_p3`: 0 if `candidate` shares a 3-segment directory prefix with `batch[0]`.
          2. `direct_chain`: 0 if `candidate` directly depends on a package in `current_batch`.
          3. `same_p2`: 0 if `candidate` shares a 2-segment directory prefix with `batch[0]`.
          4. `len(pkg_edges[candidate])`: prefers simpler packages with fewer cross-pkg deps.
          5. `candidate`: lexicographical tie-breaker for determinism.
        """
        b0 = current_batch[0]
        same_p3 = 0 if _pkg_prefix(candidate, 3) == _pkg_prefix(b0, 3) else 1
        direct_chain = 0 if (pkg_edges[candidate] & set(current_batch)) else 1
        same_p2 = 0 if _pkg_prefix(candidate, 2) == _pkg_prefix(b0, 2) else 1
        return (
            same_p3,
            direct_chain,
            same_p2,
            len(pkg_edges[candidate]),
            candidate,
        )

    def classify_batch_kind(batch: list[str], default_label: str) -> str:
        """Classifies a packed CL batch for header badge rendering."""
        if default_label == "UNBLOCKED":
            return "UNBLOCKED"
        has_3p_blocker = any(
            statuses[t][0] == "HARD_BLOCKER" and t.startswith("//third_party/")
            for p in batch
            for t in pkg_targets[p]
        )
        if has_3p_blocker:
            return "3P_BLOCKER"
        if any(pkg_is_blocker.get(p, False) for p in batch):
            return "HARD_BLOCKER"
        return "BLOCKED"

    def pack_phase(
        phase_pkgs: set[str], already_done: set[str], phase_label: str
    ) -> tuple[list[tuple[str, list[str]]], set[str]]:
        """Greedily packs `phase_pkgs` into topological CL batches of size <= `max_pkgs_per_cl`."""
        done = set(already_done)
        remaining = set(phase_pkgs)
        batches: list[list[str]] = []
        while remaining:
            ready = [p for p in remaining if pkg_edges[p].issubset(done)]
            if not ready:
                # Package-level condensation cycle: start with the package that
                # contains the lowest-wave target and fewest unmet package edges.
                ready = sorted(
                    remaining,
                    key=lambda p: (
                        min(
                            (wave_of.get(t, 0) for t in pkg_targets[p]),
                            default=0,
                        ),
                        len(pkg_edges[p] - done),
                        _pkg_prefix(p, 3),
                        p,
                    ),
                )
            else:
                ready.sort(
                    key=lambda p: (_pkg_prefix(p, 3), len(pkg_edges[p]), p)
                )
            batch = [ready[0]]
            while len(batch) < max_pkgs_per_cl:
                candidates = [
                    p
                    for p in remaining
                    if p not in batch
                    and pkg_edges[p].issubset(done | set(batch))
                ]
                # If `batch` has an unresolved package-level cycle with another
                # package in `remaining`, allow pulling that cycle partner into
                # the same CL if its only unmet dependencies are in `batch`.
                if not candidates:
                    unmet_in_batch = {
                        dep_p
                        for bp in batch
                        for dep_p in (pkg_edges[bp] - (done | set(batch)))
                        if dep_p in remaining
                    }
                    candidates = [
                        p
                        for p in unmet_in_batch
                        if (pkg_edges[p] - (done | set(batch))).issubset(
                            unmet_in_batch
                        )
                    ]
                if not candidates:
                    break
                candidates.sort(key=lambda p: affinity_score(p, batch))
                best = candidates[0]
                # Once a batch already contains >= 3 packages, stop adding
                # unrelated subsystems that neither share a 2-segment prefix
                # nor directly depend on packages in the current batch.
                if (
                    len(batch) >= 3
                    and _pkg_prefix(best, 2) != _pkg_prefix(batch[0], 2)
                    and not (pkg_edges[best] & set(batch))
                ):
                    break
                batch.append(best)
            batches.append(batch)
            done.update(batch)
            remaining -= set(batch)

        # Merge any 1-package batch into the preceding batch if topological order and max_pkgs allow
        merged: list[list[str]] = []
        done_so_far = set(already_done)
        for b in batches:
            if (
                len(b) == 1
                and merged
                and len(merged[-1]) + 1 <= max_pkgs_per_cl
                and pkg_edges[b[0]].issubset(done_so_far)
                and classify_batch_kind(b, phase_label)
                == classify_batch_kind(merged[-1], phase_label)
            ):
                merged[-1].append(b[0])
            else:
                merged.append(b)
            done_so_far.update(b)

        return [(classify_batch_kind(b, phase_label), b) for b in merged], done

    unblocked_pkgs = {p for p in pkg_targets if not pkg_blocked[p]}
    phase_b_pkgs = {p for p in pkg_targets if pkg_blocked[p]}

    phase_a, done_a = pack_phase(unblocked_pkgs, set(), "UNBLOCKED")
    phase_b, _ = pack_phase(phase_b_pkgs, done_a, "BLOCKED")
    return phase_a, phase_b, pkg_targets, pkg_edges


def main() -> int:
    """CLI entry point for analyzing a GN target or BUILD.gn migration DAG."""
    parser = argparse.ArgumentParser(
        description=(
            "Analyze recursive GN->Bazel dependency & unit-test DAG and compute "
            "topological migration waves and stacked CL plan."
        )
    )
    parser.add_argument(
        "target",
        help=(
            "GN target label (e.g. //src/lib/icu/tools/extractor:icu_data_extractor) "
            "or BUILD.gn path"
        ),
    )
    parser.add_argument(
        "--max-depth",
        type=int,
        default=-1,
        help=(
            "Maximum dependency recursion depth (-1 for unlimited depth, "
            "1 or 2 for fast shallow iteration). Default: -1"
        ),
    )
    parser.add_argument(
        "--include-upstream-tests",
        action="store_true",
        default=False,
        help=(
            "Also expand unit test targets and test_deps for all upstream "
            "packages (by default, only root package tests and upstream "
            "production deps are expanded)."
        ),
    )
    parser.add_argument(
        "--fuchsia-dir",
        default=None,
        help="Optional path to the Fuchsia checkout root directory.",
    )
    args = parser.parse_args()

    fuchsia_root = find_fuchsia_root(args.fuchsia_dir)
    raw = args.target.strip()
    is_build_gn_arg = raw == "BUILD.gn" or raw.endswith("/BUILD.gn")
    if is_build_gn_arg:
        raw_dir = raw[: -len("BUILD.gn")].rstrip("/")
        norm_dir = os.path.normpath(raw_dir.lstrip("/")).lstrip("/")
        pkg = "//" if norm_dir in ("", ".") else f"//{norm_dir}"
        display_root = f"{pkg.rstrip('/')}/BUILD.gn"
        pkg_targets = parse_build_gn_targets_and_tests(fuchsia_root, pkg)
        start_labels = (
            sorted(pkg_targets.keys())
            if pkg_targets
            else [normalize_label(pkg)]
        )
    else:
        norm = normalize_label(raw)
        pkg, _ = split_label(norm)
        display_root = norm
        pkg_targets = parse_build_gn_targets_and_tests(fuchsia_root, pkg)
        # Labels generated by a GN template (e.g. `:lib_test` from
        # `with_unit_tests = true`, or `:<fidl>_rust`) are not defined
        # literally in BUILD.gn. Analyze the defining invocation instead of
        # producing a misleading single-node plan.
        start_labels = [resolve_generated_subtarget(norm, pkg_targets)]

    rel_pkg = pkg.lstrip("/")
    gn_file = fuchsia_root / rel_pkg / "BUILD.gn"
    bazel_file = fuchsia_root / rel_pkg / "BUILD.bazel"
    if not gn_file.exists() and not bazel_file.exists():
        print(
            f"ERROR: Neither `{rel_pkg}/BUILD.gn` nor `{rel_pkg}/BUILD.bazel` "
            f"exists under `{fuchsia_root}`.",
            file=sys.stderr,
        )
        return 1

    if not is_build_gn_arg and start_labels[0] != display_root:
        print(
            f"> **Note:** `{display_root}` is generated by the GN template "
            f"invocation `{start_labels[0]}`; analyzing `{start_labels[0]}` "
            "instead.\n"
        )
    elif (
        not is_build_gn_arg
        and gn_file.exists()
        and start_labels[0] not in pkg_targets
    ):
        avail = ", ".join(f"`{k}`" for k in sorted(pkg_targets.keys()))
        print(
            f"> **Note:** Target `{start_labels[0]}` was not found directly in "
            f"`{pkg}/BUILD.gn`. Available targets in `{pkg}/BUILD.gn`: {avail or 'none'}\n"
        )

    (
        edges,
        all_gn_info,
        statuses,
        depths,
        truncated_at_depth,
    ) = build_full_dag_with_tests(
        fuchsia_root,
        start_labels,
        max_depth=args.max_depth,
        include_upstream_tests=args.include_upstream_tests,
    )
    waves, prereqs, initial_in_degree, has_cycle = kahn_topological_sort(
        edges, statuses
    )
    wave_of: dict[str, int] = {
        n: w_idx for w_idx, w in enumerate(waves) for n in w
    }

    # Compute transitive hard blockers for each node by walking reverse
    # prerequisite edges outward from every HARD_BLOCKER. This stays complete
    # even when the final Kahn wave contains a cycle (wave-order propagation
    # would miss nodes whose prerequisites appear later in the same wave).
    dependents_of: dict[str, set[str]] = defaultdict(set)
    for n, n_prereqs in prereqs.items():
        for p in n_prereqs:
            dependents_of[p].add(n)
    transitive_blockers: dict[str, set[str]] = defaultdict(set)
    for blocker in sorted(
        n for n in prereqs if statuses[n][0] == "HARD_BLOCKER"
    ):
        reached = {blocker}
        frontier = deque([blocker])
        while frontier:
            cur = frontier.popleft()
            transitive_blockers[cur].add(blocker)
            for dependent in dependents_of.get(cur, set()):
                if dependent not in reached:
                    reached.add(dependent)
                    frontier.append(dependent)

    depth_str = "unlimited (-1)" if args.max_depth < 0 else str(args.max_depth)
    print(
        f"# Topological Migration Analysis for `{display_root}` (`--max-depth={depth_str}`)\n"
    )

    by_status: dict[str, list[str]] = defaultdict(list)
    for n, (st, _) in sorted(statuses.items()):
        by_status[st].append(n)

    unblocked_in_scope = [
        n
        for n in by_status["UNMIGRATED_IN_SCOPE"]
        if not transitive_blockers.get(n)
    ]
    blocked_in_scope = [
        n
        for n in by_status["UNMIGRATED_IN_SCOPE"]
        if transitive_blockers.get(n)
    ]

    print("## 1. Node Classification Summary")
    print(f"- **Max Depth Setting:** `{depth_str}`")
    print(
        f"- **Total Relevant Nodes (Pruned at Migrated Boundaries):** {len(statuses)}"
    )
    print(
        f"- **`MIGRATED_READY` (Direct Upstream Already in Bazel):** {len(by_status['MIGRATED_READY'])}"
    )
    print(
        f"- **`UNMIGRATED_IN_SCOPE` (In-Tree Targets + Unit Tests to Migrate):** {len(by_status['UNMIGRATED_IN_SCOPE'])}"
    )
    print(
        f"  - ✅ **Unblocked / Migratable without Hard Blockers:** {len(unblocked_in_scope)}"
    )
    print(
        f"  - ⛔ **Transitively Blocked by Hard Blockers:** {len(blocked_in_scope)}"
    )
    print(
        f"- **`HARD_BLOCKER` (Out-of-Scope / Missing 3p or Custom Codegen):** {len(by_status['HARD_BLOCKER'])}"
    )
    if truncated_at_depth:
        print(
            f"- **`TRUNCATED_AT_MAX_DEPTH` (Unexpanded beyond depth={args.max_depth}):** {len(truncated_at_depth)}\n"
        )
    else:
        print("")

    if by_status["HARD_BLOCKER"]:
        print("## 2. 🚨 HARD BLOCKERS DETECTED (Within Analyzed Depth)")
        for b in by_status["HARD_BLOCKER"]:
            _, reason = statuses[b]
            print(f"- **`{b}`** (depth={depths.get(b, 0)}) -- {reason}")
        print("")

    # Section 3: Explicit CL-by-CL Migration Order (Targets in Same Step Packed into Same CL)
    phase_a_cls, phase_b_cls, cl_pkg_targets, cl_pkg_edges = plan_stacked_cls(
        edges, statuses, wave_of, max_pkgs_per_cl=5
    )
    all_cls = phase_a_cls + phase_b_cls
    pkg_to_cl: dict[str, int] = {}
    for cl_idx, (_, batch_pkgs) in enumerate(all_cls, 1):
        for p in batch_pkgs:
            pkg_to_cl[p] = cl_idx

    print(
        "## 3. Explicit CL-by-CL Migration Order (Targets in Same Step Packed into Same CL)\n"
    )
    if not all_cls:
        print(
            "✅ All analyzed targets are already migrated and ready in Bazel (`MIGRATED_READY`).\n"
        )
    else:
        print(
            "Every `CL k` below only depends on already-migrated Bazel targets, earlier CLs (`CL < k`), "
            "or targets listed earlier within the same `CL k`.\n"
        )

        def print_cl_list(cl_entries: list[tuple[int, str, list[str]]]) -> None:
            """Prints a numbered list of stacked CLs and their topologically ordered targets."""
            for cl_idx, kind, batch_pkgs in cl_entries:
                all_dep_cls = sorted(
                    {
                        pkg_to_cl[dep_p]
                        for p in batch_pkgs
                        for dep_p in cl_pkg_edges.get(p, set())
                        if dep_p in pkg_to_cl and pkg_to_cl[dep_p] != cl_idx
                    }
                )
                prior_cls = [c for c in all_dep_cls if c < cl_idx]
                forward_cls = [c for c in all_dep_cls if c > cl_idx]
                if prior_cls:
                    req_str = f" *(requires {', '.join(f'CL {c}' for c in prior_cls)})*"
                else:
                    req_str = " *(leaf CL, no prior CL required)*"
                if forward_cls:
                    req_str += (
                        f" *(package-level cycle with {', '.join(f'CL {c}' for c in forward_cls)}; "
                        "split test/subtarget across CLs)*"
                    )
                summary_str = _format_cl_summary(batch_pkgs)
                if kind == "3P_BLOCKER":
                    prefix_tag = "[3P BLOCKER] "
                elif kind == "HARD_BLOCKER":
                    prefix_tag = "[BLOCKER] "
                else:
                    prefix_tag = ""
                print(
                    f"- [ ] **CL {cl_idx}: {prefix_tag}{summary_str}**{req_str}"
                )
                # Order all targets across batch_pkgs by wave_of so intra-CL
                # targets are always listed in strict topological order.
                batch_targets = [
                    t for p in batch_pkgs for t in cl_pkg_targets[p]
                ]
                batch_targets.sort(key=lambda t: (wave_of.get(t, 0), t))
                for t in batch_targets:
                    rule = all_gn_info.get(t, {}).get("rule_type", "target")
                    unmig_deps = sorted(prereqs.get(t, set()))
                    dep_note = (
                        f" *(depends on: {', '.join(f'`{d}`' for d in unmig_deps)})*"
                        if unmig_deps
                        else ""
                    )
                    print(f"  - `{t}` (`{rule}`){dep_note}")
                print("")

        if phase_a_cls:
            print(
                f"### Phase A: Unblocked In-Tree Targets (`CL 1` - `CL {len(phase_a_cls)}`, Can Land Immediately)\n"
            )
            indexed_a = [
                (i, kind, b) for i, (kind, b) in enumerate(phase_a_cls, 1)
            ]
            print_cl_list(indexed_a)

        if phase_b_cls:
            start_b = len(phase_a_cls) + 1
            end_b = len(all_cls)
            print(
                f"### Phase B: Hard Blockers & Blocked Downstream Stack (`CL {start_b}` - `CL {end_b}`)\n"
            )
            indexed_b = [
                (i, kind, b) for i, (kind, b) in enumerate(phase_b_cls, start_b)
            ]
            print_cl_list(indexed_b)

    # Check for upstream unit-test-only dependencies (test_deps) when not expanding upstream tests
    if not args.include_upstream_tests and by_status["UNMIGRATED_IN_SCOPE"]:
        tp_map = load_third_party_map(fuchsia_root)
        extra_test_deps: dict[str, list[str]] = defaultdict(list)
        test_cycle_notes: list[str] = []
        for u in sorted(by_status["UNMIGRATED_IN_SCOPE"]):
            tdeps = all_gn_info.get(u, {}).get("test_deps", set())
            u_pkg, _ = split_label(u)
            u_cl = pkg_to_cl.get(u_pkg, 0)
            for td in sorted(tdeps):
                td_pkg, _ = split_label(td)
                td_gn_info = all_gn_info.get(td)
                if td_gn_info is None and not td_pkg.startswith(
                    "//third_party/"
                ):
                    td_gn_info = parse_build_gn_targets_and_tests(
                        fuchsia_root, td_pkg
                    ).get(td)
                td_st, _ = check_bazel_status(
                    fuchsia_root, td, tp_map, td_gn_info
                )
                if td_st == "MIGRATED_READY":
                    continue
                if td not in statuses:
                    extra_test_deps[td].append(u)
                else:
                    td_cl = pkg_to_cl.get(td_pkg, 0)
                    if td_cl > u_cl > 0:
                        test_cycle_notes.append(
                            f"- `{u}` (CL {u_cl}) has `test_deps` on `{td}` (CL {td_cl}); keep `{u}` unit tests in GN until CL {td_cl}."
                        )
        if extra_test_deps or test_cycle_notes:
            print("### Upstream Unit-Test (`test_deps`) Notes\n")
            for td, consumers in sorted(extra_test_deps.items()):
                cons_str = ", ".join(f"`{c}`" for c in consumers)
                print(
                    f"- Additional `test_deps` target `{td}` (used by unit tests of {cons_str})"
                )
            for note in test_cycle_notes:
                print(note)
            print("")

    print("## 4. Topological Migration Waves (Kahn's In-Degree Reference)")
    if not waves:
        print(
            "\n✅ All analyzed targets are already migrated and ready in Bazel (`MIGRATED_READY`)."
        )
    for idx, wave in enumerate(waves):
        if has_cycle and idx == len(waves) - 1:
            print(
                f"\n### Wave {idx} (WARNING: dependency cycle detected among remaining targets)"
            )
        else:
            print(
                f"\n### Wave {idx} (in-degree = 0 when Wave < {idx} complete)"
            )
        for n in wave:
            st, reason = statuses[n]
            rule = all_gn_info.get(n, {}).get("rule_type", "target")
            indeg = initial_in_degree.get(n, 0)
            d_val = depths.get(n, 0)
            wait_list = sorted(prereqs.get(n, set()))
            wait_str = (
                f" (waits on: {', '.join(f'`{w}`' for w in wait_list)})"
                if wait_list
                else " (initial in-degree = 0, leaf)"
            )
            trunc_str = (
                f" ⏸️ [TRUNCATED at depth={args.max_depth}]"
                if n in truncated_at_depth
                else ""
            )
            t_blockers = sorted(transitive_blockers.get(n, set()) - {n})
            if st == "HARD_BLOCKER":
                badge = "🚨 [HARD_BLOCKER]"
            elif t_blockers:
                badge = (
                    f"⛔ [BLOCKED by {', '.join(f'`{b}`' for b in t_blockers)}]"
                )
            else:
                badge = "✅ [MIGRATABLE]"
            print(
                f"- {badge} `{n}` (`{rule}`, depth={d_val}, initial in-degree={indeg}){wait_str}{trunc_str}"
            )
            print(f"  - Status: {reason}")

    print("\n## 5. Direct Upstream Dependencies Already Migrated (Pruned)")
    migrated_upstream = [
        n for n in by_status["MIGRATED_READY"] if depths.get(n, 0) > 0
    ]
    if not migrated_upstream:
        print("- *(None)*")
    for n in migrated_upstream:
        _, reason = statuses[n]
        print(f"- `{n}` (depth={depths.get(n, 0)}) -- {reason}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
